import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { screen, waitFor, within } from '@testing-library/react';
import { renderWithProviders } from '@/test/utils';
import {
  MEETING_ID,
  chatMessage,
  intelligence,
  meeting,
  serveMeeting,
} from '@/test/meetingFixtures';
import { MeetingDetailPage } from './MeetingDetailPage';

function renderPage(search = '') {
  return renderWithProviders(<MeetingDetailPage />, {
    route: `/app/meetings/${MEETING_ID}${search}`,
    path: '/app/meetings/:meetingId',
  });
}

beforeEach(() => {
  // jsdom has no object URLs and no media playback.
  URL.createObjectURL = vi.fn(() => 'blob:recording');
  URL.revokeObjectURL = vi.fn();
  vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue();
});

afterEach(() => {
  vi.restoreAllMocks();
});

describe('<MeetingDetailPage />', () => {
  it('opens on the summary, with the decisions, and says the AI wrote it', async () => {
    serveMeeting();
    renderPage();

    // The first render in the file pays for the whole page tree; a loaded
    // machine can take longer than the default 1s for that alone.
    expect(
      await screen.findByText('The team planned sprint 14.', {}, { timeout: 5_000 }),
    ).toBeInTheDocument();
    expect(
      screen.getByRole('heading', { level: 1, name: 'Sprint 14 planning' }),
    ).toBeInTheDocument();
    expect(screen.getByRole('tab', { name: 'Summary' })).toHaveAttribute('aria-selected', 'true');
    expect(screen.getByText('Build Google Calendar only this sprint')).toBeInTheDocument();
    expect(screen.getByText(/Generated by AI \(mock\)/)).toBeInTheDocument();
  });

  it('lists owned action items, flags an unknown owner, and counts the open ones', async () => {
    serveMeeting();
    const { user } = renderPage();

    const tab = await screen.findByRole('tab', { name: /Action items/ });
    expect(tab).toHaveTextContent('2 open');
    await user.click(tab);

    expect(screen.getByText('Fix the upload retry bug')).toBeInTheDocument();
    expect(screen.getByText('Grace Hopper')).toBeInTheDocument();
    expect(screen.getByText(/Due Fri/)).toBeInTheDocument();
    // A name that matched nobody in the meeting is shown, but flagged.
    expect(screen.getByText(/Sam \(not a participant\)/)).toBeInTheDocument();

    // Each item can become a task, and both at once.
    expect(
      screen.getByRole('button', { name: 'Create a task for “Fix the upload retry bug”' }),
    ).toBeEnabled();
    expect(screen.getByRole('button', { name: 'Create tasks for all (2)' })).toBeEnabled();
  });

  it('searches the transcript and highlights what it found', async () => {
    serveMeeting();
    const { user } = renderPage();

    await user.click(await screen.findByRole('tab', { name: 'Transcript' }));
    expect(screen.getByText('01:07')).toBeInTheDocument();
    expect(screen.getByText('2 lines')).toBeInTheDocument();

    await user.type(screen.getByRole('searchbox', { name: 'Search the transcript' }), 'calendar');

    expect(screen.getByText('1 of 2 lines match')).toBeInTheDocument();
    expect(screen.queryByText(/fix the upload bug/)).not.toBeInTheDocument();
    expect(screen.getByText('Calendar', { selector: 'mark' })).toBeInTheDocument();
  });

  it('plays the recording from a transcript line when one is clicked', async () => {
    const fetchMock = serveMeeting({
      meeting: {
        recording: {
          url: `/api/meetings/${MEETING_ID}/recording/audio`,
          publicId: 'x',
          durationSec: 300,
          status: 'ready',
        },
      },
    });
    const { user } = renderPage('?tab=transcript');

    // A locally stored recording needs the bearer token, so it is fetched.
    const play = await screen.findByRole('button', { name: 'Play from 01:07' });
    expect(fetchMock).toHaveBeenCalledWith(
      `/api/meetings/${MEETING_ID}/recording/audio`,
      expect.objectContaining({ headers: expect.objectContaining({ Authorization: 'Bearer t' }) }),
    );

    await user.click(play);

    const audio = screen.getByLabelText('Meeting recording') as HTMLAudioElement;
    expect(audio).toHaveAttribute('src', 'blob:recording');
    expect(audio.currentTime).toBe(67);
    expect(HTMLMediaElement.prototype.play).toHaveBeenCalled();
  });

  it('lands on a transcript line from a search result link', async () => {
    serveMeeting();
    renderPage('?tab=transcript&t=113&q=google');

    const search = await screen.findByRole('searchbox', { name: 'Search the transcript' });
    expect(search).toHaveValue('google');
    expect(screen.getByRole('tab', { name: 'Transcript' })).toHaveAttribute(
      'aria-selected',
      'true',
    );
    const line = screen.getByText('Google', { selector: 'mark' }).closest('li');
    expect(line).toHaveClass('bg-primary/10');
  });

  it('shows the chat log and reads further back on request', async () => {
    const fetchMock = serveMeeting({
      chatPages: [
        {
          messages: [chatMessage('3', 'Newest message', '2026-09-14T09:45:00.000Z')],
          nextCursor: '2026-09-14T09:45:00.000Z',
        },
        {
          messages: [chatMessage('1', 'Oldest message', '2026-09-14T09:31:00.000Z')],
          nextCursor: null,
        },
      ],
    });
    const { user } = renderPage('?tab=chat');

    expect(await screen.findByText('Newest message')).toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'Load earlier messages' }));

    const older = await screen.findByText('Oldest message');
    // Older messages go above, so the log still reads top to bottom.
    expect(older.compareDocumentPosition(screen.getByText('Newest message'))).toBe(
      Node.DOCUMENT_POSITION_FOLLOWING,
    );
    expect(fetchMock).toHaveBeenCalledWith(
      expect.stringContaining('before=2026-09-14T09%3A45%3A00.000Z'),
      expect.anything(),
    );
    expect(screen.queryByRole('button', { name: 'Load earlier messages' })).not.toBeInTheDocument();
  });

  it('explains a meeting that has no recording on the recording tab', async () => {
    serveMeeting();
    renderPage('?tab=recording');

    expect(await screen.findByText(/created from sample data/)).toBeInTheDocument();
    expect(screen.queryByLabelText('Meeting recording')).not.toBeInTheDocument();
  });

  it('walks through the pipeline steps while processing', async () => {
    serveMeeting({
      intelligence: intelligence({ aiStatus: 'transcribing', insight: null, transcript: null }),
    });
    renderPage();

    const current = await screen.findByText('Transcribing the audio');
    expect(current.closest('li')).toHaveAttribute('aria-current', 'step');
    expect(screen.getByText('Recording received').closest('li')).toHaveTextContent('(done)');
    expect(screen.getByText(/Still processing/)).toBeInTheDocument();
  });

  it('explains a failure and lets the host retry', async () => {
    const fetchMock = serveMeeting({
      intelligence: intelligence({
        aiStatus: 'failed',
        aiError: 'The AI service is rate-limiting requests. Retry in a minute.',
        insight: null,
        transcript: null,
      }),
    });
    const { user } = renderPage();

    expect(await screen.findByRole('alert')).toHaveTextContent('rate-limiting');
    await user.click(screen.getByRole('button', { name: 'Retry' }));

    await waitFor(() =>
      expect(fetchMock).toHaveBeenCalledWith(
        `/api/meetings/${MEETING_ID}/ai/retry`,
        expect.objectContaining({ method: 'POST' }),
      ),
    );
  });

  it('offers no retry and no editing to someone who is not the host', async () => {
    serveMeeting({ meeting: { isHost: false } });
    const { user } = renderPage();

    await screen.findByText('The team planned sprint 14.');
    expect(screen.queryByRole('button', { name: 'Edit summary' })).not.toBeInTheDocument();
    // Says why, instead of leaving them looking for a button.
    expect(screen.getByText(/Only the host, Demo User, can correct/)).toBeInTheDocument();

    await user.click(screen.getByRole('tab', { name: /Action items/ }));
    expect(screen.queryByRole('checkbox')).not.toBeInTheDocument();
    expect(within(screen.getByRole('tabpanel')).getAllByLabelText('Open')).toHaveLength(2);
  });

  it('does not offer Retry to someone who is not the host', async () => {
    serveMeeting({
      meeting: { isHost: false },
      intelligence: intelligence({
        aiStatus: 'failed',
        aiError: 'x',
        insight: null,
        transcript: null,
      }),
    });
    renderPage();

    expect(await screen.findByText('The host can retry from this page.')).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Retry' })).not.toBeInTheDocument();
  });

  it('says so when a meeting was never recorded', async () => {
    serveMeeting({
      meeting: { aiStatus: 'none' },
      intelligence: intelligence({ aiStatus: 'none', insight: null, transcript: null }),
    });
    renderPage();

    expect(await screen.findByText('No recording')).toBeInTheDocument();
    // Nothing to export yet, so no export controls.
    expect(screen.queryByRole('button', { name: /Copy summary/ })).not.toBeInTheDocument();
  });

  it('links a live meeting back to its room', async () => {
    serveMeeting({ meeting: meeting({ status: 'live', endedAt: null, durationSec: null }) });
    renderPage();

    expect(await screen.findByRole('link', { name: /Open the meeting room/ })).toHaveAttribute(
      'href',
      '/app/room/ABC2345',
    );
  });
});
