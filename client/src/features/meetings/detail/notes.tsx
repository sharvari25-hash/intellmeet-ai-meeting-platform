import { Info, PencilLine } from 'lucide-react';
import type { MeetingInsight } from '@intellmeet/shared';
import { formatDateTime } from '../format';

/**
 * Where the text came from. Once the host has corrected it, the page says so
 * rather than presenting a person's words as the machine's.
 */
export function EditedNote({ insight }: { insight: MeetingInsight }) {
  const origin =
    insight.provider === 'seed'
      ? 'Sample meeting: this is the hand-written reference the AI is evaluated against.'
      : `Generated by AI (${insight.provider}). AI output can be wrong; check owners and dates before acting on them.`;

  return (
    <p className="flex items-start gap-1.5 text-xs text-muted-foreground">
      {insight.editedAt ? (
        <PencilLine aria-hidden="true" className="mt-px size-3.5 shrink-0" />
      ) : (
        <Info aria-hidden="true" className="mt-px size-3.5 shrink-0" />
      )}
      <span>
        {insight.editedAt &&
          `Edited by ${insight.editedByName ?? 'the host'} on ${formatDateTime(insight.editedAt)}. `}
        {origin}
      </span>
    </p>
  );
}

/** Tells a non-host why there is no Edit button, instead of leaving them to wonder. */
export function HostOnlyNote({ hostName }: { hostName: string }) {
  return (
    <p className="text-xs text-muted-foreground">
      Only the host, {hostName}, can correct the summary and action items.
    </p>
  );
}
