import type { Meeting, MeetingIntelligence } from '@intellmeet/shared';
import { formatOffset } from '../aiStatus';
import { formatDateTime, formatDue, formatMinutes, meetingWhen } from '../format';

/**
 * A meeting's minutes, flattened into what every export format prints.
 *
 * Built once from the data already on the page - the export makes no request
 * of its own - and then rendered three ways: Markdown for a wiki or a repo,
 * PDF for a person, and plain text for the clipboard. Keeping the model
 * separate from the renderers is what makes the three agree, and what makes
 * them testable without a browser.
 */
export interface ExportModel {
  title: string;
  description: string | null;
  when: string;
  duration: string | null;
  host: string;
  participants: string[];
  summary: string | null;
  decisions: string[];
  actionItems: {
    text: string;
    owner: string | null;
    /** The owner is a name the AI heard that matches no account. */
    ownerUnmatched: boolean;
    due: string | null;
    done: boolean;
  }[];
  transcript: { at: string; speaker: string | null; text: string }[];
  /** "Generated by AI (groq), edited by Grace Hopper on …" */
  provenance: string | null;
  /** Written by a model rather than taken from the sample data. */
  aiGenerated: boolean;
}

export function buildExportModel(meeting: Meeting, intelligence: MeetingIntelligence | undefined) {
  const insight = intelligence?.insight ?? null;
  const transcript = intelligence?.transcript ?? null;

  const participants = meeting.participants.map((person) => person.name);

  const provenance = insight
    ? [
        insight.provider === 'seed'
          ? 'Sample meeting: a hand-written reference summary'
          : `Generated by AI (${insight.provider})`,
        insight.editedAt && insight.editedByName
          ? `edited by ${insight.editedByName} on ${formatDateTime(insight.editedAt)}`
          : null,
      ]
        .filter(Boolean)
        .join(', ')
    : null;

  const model: ExportModel = {
    title: meeting.title,
    description: meeting.description,
    when: formatDateTime(meetingWhen(meeting), 'Not scheduled'),
    duration: meeting.durationSec !== null ? formatMinutes(meeting.durationSec) : null,
    host: meeting.hostName,
    participants: participants.length > 0 ? participants : [meeting.hostName],
    summary: insight?.summary ?? null,
    decisions: insight?.keyDecisions ?? [],
    actionItems: (insight?.actionItems ?? []).map((item) => ({
      text: item.text,
      owner: item.assigneeName,
      ownerUnmatched: Boolean(item.assigneeName) && !item.assigneeId,
      due: item.dueDate ? formatDue(item.dueDate) : null,
      done: item.status === 'done',
    })),
    transcript: (transcript?.segments ?? []).map((segment) => ({
      at: formatOffset(segment.start),
      speaker: segment.speaker,
      text: segment.text,
    })),
    provenance,
    aiGenerated: Boolean(insight) && insight?.provider !== 'seed',
  };
  return model;
}

/** Whether there is anything worth exporting yet. */
export function hasExportableContent(model: ExportModel): boolean {
  return model.summary !== null || model.transcript.length > 0;
}

// --- Markdown -----------------------------------------------------------------

/**
 * Escapes what Markdown would otherwise interpret.
 *
 * Summaries and transcripts are other people's words: a stray `*` should not
 * turn a line italic, and a `<script>` in a transcript must stay text in any
 * viewer that renders inline HTML.
 */
export function escapeMarkdown(text: string): string {
  return text.replace(/([\\`*_[\]<>|])/g, '\\$1').replace(/^(\s*)([#+-]|\d+\.)(\s)/gm, '$1\\$2$3');
}

/** Escaped, and on one line: for a list entry or a heading. */
function inline(text: string): string {
  return escapeMarkdown(text.replace(/\s*\r?\n\s*/g, ' '));
}

function actionLine(item: ExportModel['actionItems'][number], escape: (s: string) => string) {
  const details = [
    item.owner ? `${escape(item.owner)}${item.ownerUnmatched ? ' (not a participant)' : ''}` : null,
    item.due ? `due ${item.due}` : null,
  ].filter(Boolean);
  return `${escape(item.text)}${details.length > 0 ? ` (${details.join(', ')})` : ''}`;
}

export function buildMarkdown(model: ExportModel): string {
  const lines: string[] = [`# ${inline(model.title)}`, ''];

  if (model.description) lines.push(escapeMarkdown(model.description), '');

  lines.push(`- **When:** ${model.when}`);
  if (model.duration) lines.push(`- **Duration:** ${model.duration}`);
  lines.push(`- **Host:** ${inline(model.host)}`);
  lines.push(`- **Participants:** ${model.participants.map(inline).join(', ')}`, '');

  if (model.summary) {
    // Paragraphs the host typed survive; everything else is escaped.
    lines.push('## Summary', '', escapeMarkdown(model.summary), '');
  }

  if (model.decisions.length > 0) {
    lines.push('## Key decisions', '');
    for (const decision of model.decisions) lines.push(`- ${inline(decision)}`);
    lines.push('');
  }

  if (model.actionItems.length > 0) {
    lines.push('## Action items', '');
    // GitHub-style task list: renders as checkboxes in most viewers.
    for (const item of model.actionItems) {
      lines.push(`- [${item.done ? 'x' : ' '}] ${actionLine(item, inline)}`);
    }
    lines.push('');
  }

  if (model.transcript.length > 0) {
    lines.push('## Transcript', '');
    for (const line of model.transcript) {
      const who = line.speaker ? ` **${inline(line.speaker)}:**` : '';
      lines.push(`\`${line.at}\`${who} ${inline(line.text)}`, '');
    }
  }

  if (model.provenance) {
    const caveat = model.aiGenerated ? ' AI output can be wrong.' : '';
    lines.push('---', '', `_${model.provenance}.${caveat}_`);
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

// --- Clipboard ------------------------------------------------------------------

/**
 * The summary as plain text, for pasting into a chat.
 *
 * No Markdown: most chat tools either render only part of it or show the
 * asterisks. Bullets are real bullets, which paste cleanly everywhere.
 */
export function buildPlainSummary(model: ExportModel): string {
  const sections = [`${model.title} (${model.when})`];

  if (model.summary) sections.push(`Summary\n${model.summary}`);
  if (model.decisions.length > 0) {
    sections.push(`Key decisions\n${model.decisions.map((d) => `• ${d}`).join('\n')}`);
  }
  if (model.actionItems.length > 0) {
    sections.push(
      `Action items\n${model.actionItems
        .map((item) => `${item.done ? '✓' : '•'} ${actionLine(item, (s) => s)}`)
        .join('\n')}`,
    );
  }

  return sections.join('\n\n');
}
