import { describe, expect, it } from 'vitest';
import { fileNameFrom } from '@/lib/download';
import { intelligence, meeting } from '@/test/meetingFixtures';
import { splitByQuery } from '../textMatch';
import {
  buildExportModel,
  buildMarkdown,
  buildPlainSummary,
  escapeMarkdown,
  hasExportableContent,
} from './meetingExport';
import { renderMeetingPdf } from './pdf';
import { toPdfText } from './pdfText';

const model = () => buildExportModel(meeting(), intelligence());

describe('Markdown export', () => {
  it('writes the minutes as a document with a task list and a timestamped transcript', () => {
    const markdown = buildMarkdown(model());

    expect(markdown).toMatch(/^# Sprint 14 planning\n/);
    expect(markdown).toContain('- **Host:** Demo User');
    expect(markdown).toContain('- **Participants:** Demo User, Grace Hopper');
    expect(markdown).toContain('## Summary\n\nThe team planned sprint 14.');
    expect(markdown).toContain('## Key decisions\n\n- Build Google Calendar only this sprint');
    expect(markdown).toMatch(/- \[ \] Fix the upload retry bug \(Grace Hopper, due Fri.*\)/);
    expect(markdown).toContain('- [ ] Call the vendor (Sam (not a participant))');
    expect(markdown).toContain(
      '`01:07` **Demo User:** Grace, can you fix the upload bug by Friday?',
    );
    expect(markdown).toMatch(/_Generated by AI \(mock\)\. AI output can be wrong\._\n$/);
  });

  it('marks finished items as ticked', () => {
    const data = intelligence();
    const [first] = data.insight?.actionItems ?? [];
    if (first) first.status = 'done';

    expect(buildMarkdown(buildExportModel(meeting(), data))).toContain(
      '- [x] Fix the upload retry bug',
    );
  });

  it('keeps other people’s words as text, whatever characters they use', () => {
    expect(escapeMarkdown('*not bold* <script>alert(1)</script> [link](x)')).toBe(
      '\\*not bold\\* \\<script\\>alert(1)\\</script\\> \\[link\\](x)',
    );
    expect(escapeMarkdown('# not a heading\n- not a list')).toBe(
      '\\# not a heading\n\\- not a list',
    );
  });

  it('only offers an export once there is something to export', () => {
    expect(hasExportableContent(model())).toBe(true);
    expect(
      hasExportableContent(
        buildExportModel(meeting(), intelligence({ insight: null, transcript: null })),
      ),
    ).toBe(false);
  });
});

describe('copying the summary', () => {
  it('produces plain text with real bullets, ready to paste into chat', () => {
    const text = buildPlainSummary(model());

    expect(text).toMatch(/^Sprint 14 planning \(/);
    expect(text).toContain('Summary\nThe team planned sprint 14.');
    expect(text).toContain('Key decisions\n• Build Google Calendar only this sprint');
    expect(text).toMatch(/Action items\n• Fix the upload retry bug \(Grace Hopper, due Fri/);
    // No Markdown syntax for a chat tool to show literally.
    expect(text).not.toMatch(/\*\*|##/);
  });
});

/** jsdom's Blob has no `arrayBuffer()`; its FileReader does the same job. */
function readBytes(blob: Blob): Promise<Uint8Array> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(new Uint8Array(reader.result as ArrayBuffer));
    reader.onerror = () => reject(reader.error);
    reader.readAsArrayBuffer(blob);
  });
}

describe('PDF export', () => {
  it('renders a real PDF document', async () => {
    const blob = await renderMeetingPdf(model());
    const text = new TextDecoder('latin1').decode(await readBytes(blob));

    expect(blob.type).toBe('application/pdf');
    expect(text.startsWith('%PDF-')).toBe(true);
    expect(text.trimEnd().endsWith('%%EOF')).toBe(true);
    // The document's own title, in its metadata.
    expect(text).toContain('Sprint 14 planning');
  }, 20_000);

  it('replaces characters the built-in fonts cannot draw', () => {
    expect(toPdfText('Café “quoted” – fine')).toBe('Café “quoted” – fine');
    expect(toPdfText('Şehir')).toBe('Sehir');
    expect(toPdfText('会議 ✓')).toBe('?? ?');
  });
});

describe('file names and highlighting', () => {
  it('turns a title into a safe file name', () => {
    expect(fileNameFrom('Design review: meeting summary page', 'pdf')).toBe(
      'design-review-meeting-summary-page.pdf',
    );
    expect(fileNameFrom('???', 'md')).toBe('meeting.md');
  });

  it('marks every inflection of a searched word', () => {
    expect(splitByQuery('We planned the plan.', 'planning')).toEqual([
      { text: 'We ', match: false },
      { text: 'planned', match: true },
      { text: ' the ', match: false },
      { text: 'plan', match: true },
      { text: '.', match: false },
    ]);
    expect(splitByQuery('Nothing here', '')).toEqual([{ text: 'Nothing here', match: false }]);
  });
});
